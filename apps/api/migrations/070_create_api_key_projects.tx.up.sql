CREATE TABLE api_key_projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    api_key_id bigint NOT NULL,
    project_id bigint NOT NULL,
    FOREIGN KEY (api_key_id, workspace_id) REFERENCES api_keys(id, workspace_id) ON DELETE CASCADE,
    FOREIGN KEY (project_id, workspace_id) REFERENCES projects(id, workspace_id) ON DELETE CASCADE,
    UNIQUE (api_key_id, project_id)
);
CREATE INDEX api_key_projects_workspace_idx ON api_key_projects (workspace_id, api_key_id);
CREATE INDEX api_key_projects_project_idx ON api_key_projects (project_id);
