CREATE TABLE api_keys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id text NOT NULL UNIQUE DEFAULT public_id('apk') CHECK (public_id ~ '^apk_[A-Za-z0-9]{14}$'),
    workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('workspace', 'personal')),
    owner_user_id bigint REFERENCES users(id) ON DELETE CASCADE,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    token_hash text UNIQUE CHECK (token_hash IS NULL OR token_hash ~ '^[0-9a-f]{64}$'),
    project_access text NOT NULL CHECK (project_access IN ('all', 'selected')),
    scopes text[] NOT NULL CHECK (cardinality(scopes) BETWEEN 1 AND 5 AND scopes <@ ARRAY['project.index','project.show','project.store','project.update','project.destroy']::text[] AND array_position(scopes, NULL) IS NULL),
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    updated_at timestamptz NOT NULL DEFAULT current_timestamp,
    expires_at timestamptz,
    last_used_at timestamptz,
    revoked_at timestamptz,
    CHECK ((kind = 'personal' AND owner_user_id IS NOT NULL) OR (kind = 'workspace' AND owner_user_id IS NULL)),
    CHECK (project_access <> 'selected' OR NOT ('project.store' = ANY(scopes))),
    CHECK (expires_at IS NULL OR expires_at BETWEEN created_at + interval '1 hour' AND created_at + interval '8760 hours'),
    CHECK ((revoked_at IS NULL AND token_hash IS NOT NULL) OR (revoked_at IS NOT NULL AND token_hash IS NULL)),
    UNIQUE (id, workspace_id)
);
CREATE INDEX api_keys_workspace_created_idx ON api_keys (workspace_id, created_at DESC, id DESC);
CREATE INDEX api_keys_owner_created_idx ON api_keys (owner_user_id, created_at DESC, id DESC) WHERE owner_user_id IS NOT NULL;
CREATE INDEX api_keys_ended_idx ON api_keys ((LEAST(expires_at, revoked_at))) WHERE expires_at IS NOT NULL OR revoked_at IS NOT NULL;
