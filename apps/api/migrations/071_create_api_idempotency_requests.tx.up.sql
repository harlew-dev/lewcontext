CREATE TABLE api_idempotency_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id bigint NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    api_key_id bigint NOT NULL,
    operation text NOT NULL CHECK (operation = 'project.store'),
    value_hash text NOT NULL CHECK (value_hash ~ '^[0-9a-f]{64}$'),
    input_hash text NOT NULL CHECK (input_hash ~ '^[0-9a-f]{64}$'),
    project_public_id text NOT NULL CHECK (project_public_id ~ '^prj_[A-Za-z0-9]{14}$'),
    response jsonb NOT NULL CHECK (jsonb_typeof(response) = 'object' AND octet_length(response::text) <= 8192),
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    expires_at timestamptz NOT NULL DEFAULT current_timestamp + interval '24 hours',
    CHECK (expires_at = created_at + interval '24 hours'),
    FOREIGN KEY (api_key_id, workspace_id) REFERENCES api_keys(id, workspace_id) ON DELETE CASCADE,
    UNIQUE (api_key_id, workspace_id, operation, value_hash)
);
CREATE INDEX api_idempotency_requests_workspace_idx ON api_idempotency_requests (workspace_id, expires_at);
CREATE INDEX api_idempotency_requests_expiry_idx ON api_idempotency_requests (expires_at);
