package factory

import (
	"context"
	"github.com/brianvoe/gofakeit/v7"
	"github.com/uptrace/bun"
	"lewcontext/api/internal/auth"
	"time"
)

type Workspace struct {
	bun.BaseModel `bun:"table:workspaces,alias:w"`
	ID            int64  `bun:",pk,autoincrement"`
	PublicID      string `bun:",nullzero"` // generated by PostgreSQL
	Name          string
	CreatedAt     time.Time `bun:",nullzero,notnull,default:current_timestamp"`
	UpdatedAt     time.Time `bun:",nullzero,notnull,default:current_timestamp"`
}

// WorkspaceUser is a membership: a user's role in a workspace.
type WorkspaceUser struct {
	bun.BaseModel `bun:"table:workspace_user,alias:m"`
	ID            int64 `bun:",pk,autoincrement"`
	UserID        int64 `bun:",notnull"`
	WorkspaceID   int64 `bun:",notnull"`
	Role          auth.Role
	CreatedAt     time.Time `bun:",nullzero,notnull,default:current_timestamp"`
}

// Workspaces builds workspaces named after fake companies, created in the
// last year. Add members with WorkspaceUsers, or use WorkspaceFor.
var Workspaces = Define(func(f *gofakeit.Faker) Workspace {
	now := time.Now()
	created := f.DateRange(now.AddDate(-1, 0, 0), now)
	return Workspace{
		Name:      truncate(f.Company(), 80),
		CreatedAt: created,
		UpdatedAt: f.DateRange(created, now),
	}
})

// WorkspaceUsers builds memberships with a random role. Set UserID and
// WorkspaceID, or use MemberOf.
var WorkspaceUsers = Define(func(f *gofakeit.Faker) WorkspaceUser {
	return WorkspaceUser{Role: auth.Roles[f.IntN(len(auth.Roles))]}
})

// WorkspaceFor creates a workspace owned by a user, as the API does when the
// user creates one.
func WorkspaceFor(ctx context.Context, db bun.IDB, f *gofakeit.Faker, userID int64, states ...func(*Workspace)) (Workspace, error) {
	factory := Workspaces
	for _, state := range states {
		factory = factory.State(state)
	}
	workspace, err := factory.CreateOne(ctx, db, f)
	if err != nil {
		return Workspace{}, err
	}
	_, err = MemberOf(ctx, db, f, userID, workspace.ID, auth.RoleOwner)
	return workspace, err
}

// MemberOf adds a user to a workspace with a role.
func MemberOf(ctx context.Context, db bun.IDB, f *gofakeit.Faker, userID, workspaceID int64, role auth.Role) (WorkspaceUser, error) {
	return WorkspaceUsers.State(func(m *WorkspaceUser) {
		m.UserID, m.WorkspaceID, m.Role = userID, workspaceID, role
	}).CreateOne(ctx, db, f)
}

// Named sets a workspace's name.
func Named(name string) func(*Workspace) {
	return func(w *Workspace) { w.Name = name }
}
