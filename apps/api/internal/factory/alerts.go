package factory

import (
	"encoding/json"
	"github.com/brianvoe/gofakeit/v7"
	"github.com/uptrace/bun"
	"time"
)

type Alert struct {
	bun.BaseModel  `bun:"table:alerts,alias:alt"`
	ID             int64           `bun:",pk,autoincrement"`
	PublicID       string          `bun:",nullzero"` // generated by PostgreSQL
	Signal         string          `bun:",notnull"`
	Level          string          `bun:",notnull"`
	OpenedAt       time.Time       `bun:",notnull"`
	LastValue      float64         `bun:",notnull"`
	PeakValue      float64         `bun:",notnull"`
	Details        json.RawMessage `bun:"type:jsonb,notnull"`
	Notified       string          `bun:",notnull"`
	LastNotifiedAt *time.Time
	// MailTimes is the database's default ('[]'), read back only.
	MailTimes      json.RawMessage `bun:"mail_times,type:jsonb,scanonly"`
	AcknowledgedAt *time.Time
	AcknowledgedBy *int64
	SilencedUntil  *time.Time
	SilencedBy     *int64
	ResolvedAt     *time.Time
}

// Alerts builds open warnings on the failed sign-ins signal, opened in the
// last hour and emailed then. Use AlertOn for another signal, and the
// states below for the rest.
var Alerts = Define(func(f *gofakeit.Faker) Alert {
	opened := f.DateRange(time.Now().Add(-time.Hour), time.Now().Add(-time.Minute))
	value := float64(f.IntRange(100, 900))
	return Alert{
		Signal: "auth.failed_sign_ins", Level: "warn", OpenedAt: opened,
		LastValue: value, PeakValue: value, Details: json.RawMessage(`{}`),
		Notified: "mail", LastNotifiedAt: &opened,
	}
})

// AlertOn sets the alert's signal and level.
func AlertOn(signal, level string) func(*Alert) {
	return func(a *Alert) { a.Signal, a.Level = signal, level }
}

// AlertOpenedAt sets when it opened (and was emailed, if it was).
func AlertOpenedAt(at time.Time) func(*Alert) {
	return func(a *Alert) {
		a.OpenedAt = at
		if a.LastNotifiedAt != nil {
			a.LastNotifiedAt = &at
		}
	}
}

// AlertResolvedAt resolves it at at.
func AlertResolvedAt(at time.Time) func(*Alert) {
	return func(a *Alert) {
		if a.OpenedAt.After(at) {
			a.OpenedAt = at.Add(-time.Minute)
		}
		a.ResolvedAt = &at
	}
}

// AlertNotified sets how its opening was told: mail, held, digest or quiet
// (no email then).
func AlertNotified(notified string) func(*Alert) {
	return func(a *Alert) {
		a.Notified = notified
		if notified == "quiet" || notified == "held" {
			a.LastNotifiedAt = nil
		}
	}
}

// AlertAcknowledgedBy acknowledges it, by the admin userID.
func AlertAcknowledgedBy(userID int64) func(*Alert) {
	return func(a *Alert) {
		now := time.Now()
		a.AcknowledgedAt, a.AcknowledgedBy = &now, &userID
	}
}

// AlertSilencedUntil silences it until until, by the admin userID.
func AlertSilencedUntil(until time.Time, userID int64) func(*Alert) {
	return func(a *Alert) { a.SilencedUntil, a.SilencedBy = &until, &userID }
}
