package factory

import (
	"github.com/brianvoe/gofakeit/v7"
	"github.com/uptrace/bun"
	"time"
)

// AdminAlertSubscription is one signal an admin opted into by email.
type AdminAlertSubscription struct {
	bun.BaseModel `bun:"table:admin_alert_subscriptions"`
	ID            int64 `bun:",pk,autoincrement"`
	AdminUserID   int64
	Signal        string
	MinLevel      string
	Events        []string `bun:",array"`
}

// AdminAlertSubscriptions builds a subscription to warnings and critical on
// the latency signal; set AdminUserID, and Signal or MinLevel as needed.
var AdminAlertSubscriptions = Define(func(f *gofakeit.Faker) AdminAlertSubscription {
	return AdminAlertSubscription{Signal: "http.latency_p95", MinLevel: "warn", Events: allAlertEvents()}
})

// allAlertEvents is every kind of alert event an email can be about.
func allAlertEvents() []string {
	return []string{"opened", "escalated", "recovered", "reopened", "resolved", "reminded"}
}

// SubscribedToEvents limits a subscription to the event kinds given.
func SubscribedToEvents(kinds ...string) func(*AdminAlertSubscription) {
	return func(s *AdminAlertSubscription) { s.Events = append([]string{}, kinds...) }
}

// SubscribedTo subscribes the admin userID to signal at level.
func SubscribedTo(userID int64, signal, level string) func(*AdminAlertSubscription) {
	return func(s *AdminAlertSubscription) { s.AdminUserID, s.Signal, s.MinLevel = userID, signal, level }
}

// AlertWebhook has its own model. Its URL and key are sealed ciphertext the
// test makes itself (or leaves unreadable on purpose).
type AlertWebhook struct {
	bun.BaseModel    `bun:"table:alert_webhooks"`
	ID               int64  `bun:",pk,autoincrement"`
	PublicID         string `bun:",nullzero"` // generated by PostgreSQL
	Kind             string
	Name             string
	SealedURL        []byte
	Format           string
	SealedKey        []byte `bun:",nullzero"`
	KeyID            string
	SealedOverlapKey []byte `bun:",nullzero"`
	OverlapKeyID     string
	OverlapUntil     *time.Time
	Signals          []string `bun:",array"`
	Events           []string `bun:",array"`
	Enabled          bool
	DeliveryRevision int64
	Revision         int64
	PostTimes        []byte `bun:"post_times,type:jsonb,scanonly"`
	CreatedBy        *int64
	UpdatedBy        *int64
	CreatedAt        time.Time `bun:",nullzero,default:current_timestamp"`
	UpdatedAt        time.Time `bun:",nullzero,default:current_timestamp"`
}

// AlertWebhooks builds an enabled JSON webhook receiving nothing yet (an
// empty selection sends nothing), with unreadable sealed fields.
var AlertWebhooks = Define(func(f *gofakeit.Faker) AlertWebhook {
	return AlertWebhook{Kind: "webhook", Name: "Hook " + f.UUID()[:8], SealedURL: []byte{1, 2, 3}, Format: "json", SealedKey: []byte{1, 2, 3},
		KeyID: "key_abcdefgh", Signals: []string{}, Events: []string{}, Enabled: true, DeliveryRevision: 1, Revision: 1}
})

// WebhookFor selects what a webhook receives.
func WebhookFor(signals, events []string) func(*AlertWebhook) {
	return func(w *AlertWebhook) { w.Signals, w.Events = signals, events }
}
