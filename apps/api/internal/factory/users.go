package factory

import (
	"fmt"
	"github.com/brianvoe/gofakeit/v7"
	"github.com/uptrace/bun"
	"lewcontext/api/internal/auth"
	"strings"
	"sync"
	"time"
)

// DefaultPassword signs in every fake user unless a seeder sets another hash.
const DefaultPassword = "correct horse battery staple"

// Argon2id is deliberately slow, so all fake users share one hash per process.
var defaultHash = sync.OnceValues(func() (string, error) {
	return auth.HashPassword(DefaultPassword)
})

type User struct {
	bun.BaseModel `bun:"table:users,alias:u"`
	ID            int64  `bun:",pk,autoincrement"`
	PublicID      string `bun:",nullzero"` // generated by PostgreSQL
	Name          string
	Email         string
	PasswordHash  string
	CreatedAt     time.Time `bun:",nullzero,notnull,default:current_timestamp"`
	// EmailVerifiedAt is set: accounts made with EMAIL_VERIFICATION on are
	// always verified. Unverified clears it.
	EmailVerifiedAt *time.Time
	// The policy versions agreed to at sign-up, and when: nil, as for an
	// account made with POLICIES off, unless AgreedToPolicies.
	TermsOfServiceVersion *time.Time
	PrivacyPolicyVersion  *time.Time
	PoliciesAcceptedAt    *time.Time
	// LastSeenAt is nil (never signed in) unless a test sets it.
	LastSeenAt *time.Time
}

// Users builds accounts with unique, valid, lowercase emails.
var Users = Define(func(f *gofakeit.Faker) User {
	first, last := f.FirstName(), f.LastName()
	now := time.Now()
	created := f.DateRange(now.AddDate(-1, 0, 0), now)
	return User{
		Name:            first + " " + last,
		Email:           fmt.Sprintf("%s.%s.%s@example.test", slug(first), slug(last), strings.ToLower(f.LetterN(6))),
		PasswordHash:    mustHash(),
		CreatedAt:       created,
		EmailVerifiedAt: &created,
	}
})

// Unverified is an account that never verified its email, as one made while
// EMAIL_VERIFICATION was off.
func Unverified(u *User) {
	u.EmailVerifiedAt = nil
}

// AgreedToPolicies is an account that agreed to these versions (YYYY-MM-DD)
// of the terms of service and privacy policy when it was created.
func AgreedToPolicies(terms, privacy string) func(*User) {
	return func(u *User) {
		u.TermsOfServiceVersion, u.PrivacyPolicyVersion = mustDate(terms), mustDate(privacy)
		accepted := u.CreatedAt
		u.PoliciesAcceptedAt = &accepted
	}
}

// mustDate parses a version, panicking on a typo in a test.
func mustDate(version string) *time.Time {
	d, err := time.Parse(time.DateOnly, version)
	if err != nil {
		panic(fmt.Sprintf("policy version %q: %v", version, err))
	}
	return &d
}

// WithPasswordHash signs a user in with another password's hash.
func WithPasswordHash(hash string) func(*User) {
	return func(u *User) { u.PasswordHash = hash }
}

// mustHash panics only if the system random source fails.
func mustHash() string {
	hash, err := defaultHash()
	if err != nil {
		panic(fmt.Sprintf("hash fake user password: %v", err))
	}
	return hash
}

// slug keeps the ASCII letters of a name for an email local part.
func slug(s string) string {
	return strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' {
			return r
		}
		return -1
	}, strings.ToLower(s))
}
