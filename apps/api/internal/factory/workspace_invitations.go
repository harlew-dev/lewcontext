package factory

import (
	"database/sql"
	"fmt"
	"github.com/brianvoe/gofakeit/v7"
	"github.com/uptrace/bun"
	"lewcontext/api/internal/auth"
	"strings"
	"time"
)

type WorkspaceInvitation struct {
	bun.BaseModel `bun:"table:workspace_invitations,alias:i"`
	ID            int64  `bun:",pk,autoincrement"`
	PublicID      string `bun:",nullzero"` // generated by PostgreSQL
	WorkspaceID   int64  `bun:",notnull"`
	Email         string
	Role          auth.Role
	InvitedBy     int64          `bun:",nullzero"`
	TokenHash     sql.NullString `bun:"token_hash"`
	SentAt        sql.NullTime
	CreatedAt     time.Time `bun:",nullzero,notnull,default:current_timestamp"`
	ExpiresAt     time.Time `bun:",notnull"`
	// Token is the raw token in the emailed link, set by Sent; like a real
	// one, only its digest is stored.
	Token string `bun:"-"`
}

// WorkspaceInvitations builds live invitations, not yet sent, to unique
// addresses at example.test, as admin, member or viewer. Set WorkspaceID, or
// use InvitationsTo.
var WorkspaceInvitations = Define(func(f *gofakeit.Faker) WorkspaceInvitation {
	roles := []auth.Role{auth.RoleAdmin, auth.RoleMember, auth.RoleViewer}
	return WorkspaceInvitation{
		Email:     fmt.Sprintf("invitee.%s@example.test", strings.ToLower(f.LetterN(10))),
		Role:      roles[f.IntN(len(roles))],
		ExpiresAt: time.Now().Add(7 * 24 * time.Hour),
	}
})

// InvitationsTo builds invitations to the workspace.
func InvitationsTo(workspaceID int64) Factory[WorkspaceInvitation] {
	return WorkspaceInvitations.State(func(i *WorkspaceInvitation) { i.WorkspaceID = workspaceID })
}

// Sent gives the invitation an emailed link: a fresh token, kept raw in Token.
func Sent(i *WorkspaceInvitation) {
	i.Token = mustToken()
	i.TokenHash = sql.NullString{String: auth.Digest(i.Token), Valid: true}
	i.SentAt = sql.NullTime{Time: time.Now(), Valid: true}
}

// ExpiredInvitation is past its expiry.
func ExpiredInvitation(i *WorkspaceInvitation) {
	i.ExpiresAt = time.Now().Add(-time.Second)
}

// InvitedAs sets the invitation's email and role.
func InvitedAs(email string, role auth.Role) func(*WorkspaceInvitation) {
	return func(i *WorkspaceInvitation) { i.Email, i.Role = email, role }
}
