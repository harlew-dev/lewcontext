package factory

import (
	"github.com/brianvoe/gofakeit/v7"
	"github.com/uptrace/bun"
	"time"
)

type Event struct {
	bun.BaseModel `bun:"table:events,alias:e"`
	ID            int64  `bun:",pk,autoincrement"`
	PublicID      string `bun:",nullzero"` // generated by PostgreSQL
	Name          string
	ActorID       int64          `bun:",nullzero"`
	UserID        int64          `bun:",nullzero"`
	WorkspaceID   int64          `bun:",nullzero"`
	Payload       map[string]any `bun:"type:jsonb"`
	IP            string         `bun:"ip,type:inet,nullzero"`
	RequestID     string
	UserAgent     string
	// MinimisedAt is when the pseudonymise target minimised it; zero for
	// one it hasn't (Minimised sets it).
	MinimisedAt time.Time `bun:",nullzero"`
	// AdminRequest marks an event recorded in an admin dashboard request.
	AdminRequest bool
	CreatedAt    time.Time `bun:",nullzero,notnull,default:current_timestamp"`
}

// Events builds rate_limit.reached events from the last 90 days, which need
// no other records. Use a state for events about a user or workspace.
var Events = Define(func(f *gofakeit.Faker) Event {
	now := time.Now()
	created := f.DateRange(now.AddDate(0, 0, -90), now)
	return Event{
		Name: "rate_limit.reached",
		Payload: map[string]any{
			"limit":    "auth:per-ip:block",
			"window":   900,
			"resetsAt": created.Add(15 * time.Minute),
		},
		IP:        f.IPv4Address(),
		RequestID: "req_" + f.LetterN(14),
		UserAgent: truncate(f.UserAgent(), 256),
		CreatedAt: created,
	}
})

// EventOf makes events named name with payload, which identifies records by
// public ID as the store's events do.
func EventOf(name string, payload map[string]any) func(*Event) {
	return func(e *Event) { e.Name, e.Payload = name, payload }
}
